# usage: python3 srt_txt.py <work>/data.json <out_dir>  -> maratib-aldeen.srt + maratib-aldeen.txt
import json, sys
D = json.load(open(sys.argv[1])); out = sys.argv[2]
ts = lambda t: f'{int(t//3600):02d}:{int(t%3600//60):02d}:{int(t%60):02d},{int(round(t%1*1000))%1000:03d}'
srt = []
for i, l in enumerate(D['lines'], 1):
    srt.append(f"{i}\n{ts(l['s'])} --> {ts(l['e'])}\n{' '.join(D['words'][k]['w'] for k in l['words'])}\n")
open(f'{out}/maratib-aldeen.srt', 'w').write('\n'.join(srt))
